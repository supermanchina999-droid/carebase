// CareBase Core Component - Play Session Notes
// 2-minute play session documentation for Play Therapists

import React, { useState } from 'react';

const PLAY_BEHAVIORS = [
  { id: 'pretend_play', label: 'Pretend Play', icon: '🎭' },
  { id: 'stacking', label: 'Stacking/Building', icon: '🧱' },
  { id: 'aggressive_play', label: 'Aggressive Play', icon: '⚔️' },
  { id: 'exploratory', label: 'Exploratory', icon: '🔍' },
  { id: 'sensory', label: 'Sensory Play', icon: '✋' },
  { id: 'art', label: 'Art/Creative', icon: '🎨' },
  { id: 'storytelling', label: 'Storytelling', icon: '📖' },
  { id: 'repetitive', label: 'Repetitive Play', icon: '🔄' },
  { id: 'withdrawn', label: 'Withdrawn/Quiet', icon: '🤫' },
  { id: 'cooperative', label: 'Cooperative Play', icon: '🤝' },
];

const EMOTIONS = [
  { id: 'happy', label: 'Happy', icon: '😊' },
  { id: 'anxious', label: 'Anxious', icon: '😰' },
  { id: 'frustrated', label: 'Frustrated', icon: '😤' },
  { id: 'sad', label: 'Sad', icon: '😢' },
  { id: 'angry', label: 'Angry', icon: '😠' },
  { id: 'calm', label: 'Calm', icon: '😌' },
  { id: 'excited', label: 'Excited', icon: '🤩' },
  { id: 'withdrawn', label: 'Withdrawn', icon: '😶' },
];

const MILESTONES = [
  { id: 'symbolic_play', label: 'Symbolic Play', age: '2-4' },
  { id: 'pretend_play', label: 'Pretend Play', age: '3-5' },
  { id: 'turn_taking', label: 'Turn-Taking', age: '3-5' },
  { id: 'emotional_regulation', label: 'Emotional Regulation', age: '4-6' },
  { id: 'cooperative_play', label: 'Cooperative Play', age: '4-6' },
  { id: 'rule_based_play', label: 'Rule-Based Play', age: '6-8' },
  { id: 'abstract_thinking', label: 'Abstract Thinking', age: '8-12' },
  { id: 'self_expression', label: 'Self-Expression', age: '3-12' },
  { id: 'problem_solving', label: 'Problem Solving', age: '4-8' },
  { id: 'social_skills', label: 'Social Skills', age: '3-12' },
];

const TOYS = [
  { id: 'dollhouse', name: 'Dollhouse', category: 'pretend_play' },
  { id: 'blocks', name: 'Building Blocks', category: 'building' },
  { id: 'art_supplies', name: 'Art Supplies', category: 'art' },
  { id: 'puppets', name: 'Puppets', category: 'pretend_play' },
  { id: 'sand_tray', name: 'Sand Tray', category: 'sensory' },
  { id: 'board_games', name: 'Board Games', category: 'rule_based' },
  { id: 'clay', name: 'Play-Doh/Clay', category: 'sensory' },
  { id: 'action_figures', name: 'Action Figures', category: 'pretend_play' },
];

export default function PlaySessionNotes({ client, onSave }) {
  const [toysUsed, setToysUsed] = useState([]);
  const [behaviors, setBehaviors] = useState([]);
  const [emotions, setEmotions] = useState([]);
  const [milestones, setMilestones] = useState([]);
  const [therapistNotes, setTherapistNotes] = useState('');
  const [duration, setDuration] = useState(30);
  const [saving, setSaving] = useState(false);

  const toggleItem = (list, setList, item) => {
    if (list.includes(item)) setList(list.filter(i => i !== item));
    else setList([...list, item]);
  };

  const generateStructuredNote = () => {
    const toyNames = toysUsed.map(t => t.name).join(', ');
    const behaviorLabels = behaviors.map(b => PLAY_BEHAVIORS.find(pb => pb.id === b)?.label).join(', ');
    const emotionLabels = emotions.map(e => EMOTIONS.find(em => em.id === e)?.label).join(', ');
    const milestoneLabels = milestones.map(m => MILESTONES.find(ms => ms.id === m)?.label).join(', ');
    return 'Play Session Note - ' + client.first_name + ' ' + client.last_name + '\n' +
      'Date: ' + new Date().toLocaleDateString() + '\n' +
      'Duration: ' + duration + ' minutes\n\n' +
      'Toys Used: ' + (toyNames || 'None selected') + '\n' +
      'Play Behaviors: ' + (behaviorLabels || 'None selected') + '\n' +
      'Emotional Responses: ' + (emotionLabels || 'None selected') + '\n' +
      'Developmental Milestones: ' + (milestoneLabels || 'None selected') + '\n\n' +
      'Therapist Observations:\n' + (therapistNotes || 'No additional notes.') + '\n\n---\nAuto-generated by CareBase';
  };

  const handleSave = async () => {
    setSaving(true);
    const sessionData = {
      client_id: client.id,
      session_date: new Date().toISOString().split('T')[0],
      session_duration: duration,
      toys_used: toysUsed.map(t => t.name),
      play_behaviors: behaviors,
      emotional_responses: emotions,
      developmental_milestones: milestones,
      therapist_notes: therapistNotes,
      structured_note: generateStructuredNote(),
    };
    await onSave(sessionData);
    setSaving(false);
  };

  return (
    <div className="max-w-4xl mx-auto p-6 bg-white rounded-2xl shadow-lg">
      <div className="mb-6">
        <h2 className="text-2xl font-bold">Play Session Notes</h2>
        <p className="text-gray-500">{client.first_name} {client.last_name} — {new Date().toLocaleDateString()}</p>
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Duration (min)</label>
        <input type="number" value={duration} onChange={(e) => setDuration(parseInt(e.target.value) || 30)} className="w-24 px-3 py-2 border rounded-lg" />
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Toys Used</label>
        <div className="flex flex-wrap gap-2">
          {TOYS.map(toy => (
            <button key={toy.id} onClick={() => toggleItem(toysUsed, setToysUsed, toy)}
              className={"px-3 py-1.5 rounded-full text-sm " + (toysUsed.find(t => t.id === toy.id) ? "bg-blue-500 text-white" : "bg-gray-100 hover:bg-gray-200")}>
              {toy.name}
            </button>
          ))}
        </div>
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Play Behaviors</label>
        <div className="flex flex-wrap gap-2">
          {PLAY_BEHAVIORS.map(b => (
            <button key={b.id} onClick={() => toggleItem(behaviors, setBehaviors, b.id)}
              className={"px-3 py-1.5 rounded-full text-sm " + (behaviors.includes(b.id) ? "bg-purple-500 text-white" : "bg-gray-100 hover:bg-gray-200")}>
              {b.icon} {b.label}
            </button>
          ))}
        </div>
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Emotional Responses</label>
        <div className="flex flex-wrap gap-2">
          {EMOTIONS.map(e => (
            <button key={e.id} onClick={() => toggleItem(emotions, setEmotions, e.id)}
              className={"px-3 py-1.5 rounded-full text-sm " + (emotions.includes(e.id) ? "bg-teal-500 text-white" : "bg-gray-100 hover:bg-gray-200")}>
              {e.icon} {e.label}
            </button>
          ))}
        </div>
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Developmental Milestones</label>
        <div className="flex flex-wrap gap-2">
          {MILESTONES.map(m => (
            <button key={m.id} onClick={() => toggleItem(milestones, setMilestones, m.id)}
              className={"px-3 py-1.5 rounded-full text-sm " + (milestones.includes(m.id) ? "bg-green-500 text-white" : "bg-gray-100 hover:bg-gray-200")}>
              {m.label} ({m.age})
            </button>
          ))}
        </div>
      </div>
      <div className="mb-6">
        <label className="block text-sm font-medium mb-2">Additional Notes</label>
        <textarea value={therapistNotes} onChange={(e) => setTherapistNotes(e.target.value)} rows={4}
          className="w-full px-3 py-2 border rounded-lg" placeholder="Additional observations..." />
      </div>
      <div className="mb-6 p-4 bg-gray-50 rounded-lg">
        <h3 className="text-sm font-medium mb-2">Preview</h3>
        <pre className="text-xs whitespace-pre-wrap font-mono">{generateStructuredNote()}</pre>
      </div>
      <button onClick={handleSave} disabled={saving}
        className="w-full py-3 bg-blue-600 text-white rounded-lg font-semibold hover:bg-blue-700 disabled:opacity-50">
        {saving ? 'Saving...' : 'Save Session Note'}
      </button>
    </div>
  );
}